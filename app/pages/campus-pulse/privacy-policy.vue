<script setup>
import { onMounted, nextTick } from "vue";

useHead({
  title: "Privacy Policy — Campus Pulse",
  meta: [
    {
      name: "description",
      content:
        "Read the Campus Pulse Privacy Policy to learn how we collect, use, and protect your data.",
    },
  ],
});

onMounted(async () => {
  if (!import.meta.client) return;
  await nextTick();

  const { gsap } = await import("gsap");
  const { ScrollTrigger } = await import("gsap/ScrollTrigger");
  gsap.registerPlugin(ScrollTrigger);

  const title = document.querySelector(".cp-doc-title");
  if (title) {
    gsap.from(title, { y: 30, opacity: 0, duration: 0.7, ease: "power3.out" });
  }

  document.querySelectorAll(".cp-doc-card").forEach((card) => {
    gsap.from(card, {
      y: 25,
      opacity: 0,
      duration: 0.5,
      ease: "power2.out",
      scrollTrigger: {
        trigger: card,
        start: "top 92%",
        toggleActions: "play none none none",
        once: true,
      },
    });
  });
});
</script>

